const readStoredLocale = () => {
    if (typeof window === 'undefined') {
        return DEFAULT_LOCALE;
    }

    const stored = window.localStorage.getItem(STORAGE_KEY);

    return stored === 'ar' || stored === 'en' ? stored : DEFAULT_LOCALE;
};

const locale = ref(readStoredLocale());

const applyDocumentLanguage = (value) => {
    if (typeof document === 'undefined') {
        return;
    }

    document.documentElement.lang = value;
    document.documentElement.dir = value === 'ar' ? 'rtl' : 'ltr';
};

applyDocumentLanguage(locale.value);

export function useAdminLocale() {
    const setLocale = (value) => {
        if (value !== 'ar' && value !== 'en') {
            return;
        }

        locale.value = value;
        applyDocumentLanguage(value);

        if (typeof window !== 'undefined') {
            window.localStorage.setItem(STORAGE_KEY, value);
        }
    };

    const t = (value, replacements = null) => {
        if (value === null || value === undefined || value === '') {
            return value;
        }

        const dictionary = messages[locale.value] ?? messages.en;

        const translatedValue = dictionary[value] ?? value;

        if (!replacements || typeof translatedValue !== 'string') {
            return translatedValue;
        }

        return Object.entries(replacements).reduce((result, [key, replacementValue]) => {
            return result.replaceAll(`:${key}`, String(replacementValue));
        }, translatedValue);
    };

    const languageOptions = computed(() => [
        { value: 'en', label: 'EN' },
        { value: 'ar', label: 'AR' },
    ]);

    return {
        locale: computed(() => locale.value),
        isArabic: computed(() => locale.value === 'ar'),
        setLocale,
        t,
        languageOptions,
    };
}