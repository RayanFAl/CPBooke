const readStoredLocale = () => {
    if (typeof window === 'undefined') {
        return DEFAULT_LOCALE;
    }

    const stored = window.localStorage.getItem(STORAGE_KEY);

    return stored === 'ar' || stored === 'en' ? stored : DEFAULT_LOCALE;
};

const locale = ref(readStoredLocale());

const applyDocumentLanguage = (value) => {
    if (typeof document === 'undefined') {
        return;
    }

    document.documentElement.lang = value;
    document.documentElement.dir = value === 'ar' ? 'rtl' : 'ltr';
};

applyDocumentLanguage(locale.value);

export function useAdminLocale() {
    const setLocale = (value) => {
        if (value !== 'ar' && value !== 'en') {
            return;
        }

        locale.value = value;
        applyDocumentLanguage(value);

        if (typeof window !== 'undefined') {
            window.localStorage.setItem(STORAGE_KEY, value);
        }
    };

    const t = (value, replacements = null) => {
        if (value === null || value === undefined || value === '') {
            return value;
        }

        const dictionary = messages[locale.value] ?? messages.en;

        const translatedValue = dictionary[value] ?? value;

        if (!replacements || typeof translatedValue !== 'string') {
            return translatedValue;
        }

        return Object.entries(replacements).reduce((result, [key, replacementValue]) => {
            return result.replaceAll(`:${key}`, String(replacementValue));
        }, translatedValue);
    };

    const swapDirectionalMarks = (value) => {
        return value
            .replaceAll('&laquo;', '\u0001')
            .replaceAll('&raquo;', '&laquo;')
            .replaceAll('\u0001', '&raquo;')
            .replaceAll('«', '\u0001')
            .replaceAll('»', '«')
            .replaceAll('\u0001', '»')
            .replaceAll('&lsaquo;', '\u0001')
            .replaceAll('&rsaquo;', '&lsaquo;')
            .replaceAll('\u0001', '&rsaquo;')
            .replaceAll('‹', '\u0001')
            .replaceAll('›', '‹')
            .replaceAll('\u0001', '›');
    };

    const paginationLabel = (value) => {
        if (locale.value !== 'ar' || typeof value !== 'string') {
            return value;
        }

        return swapDirectionalMarks(value);
    };

    const languageOptions = computed(() => [
        { value: 'en', label: 'EN' },
        { value: 'ar', label: 'AR' },
    ]);

    const settlementStatusLabel = (status) => {
        const labels = {
            en: {
                draft: 'Draft',
                open: 'Open',
                pending_review: 'In review',
                approved: 'Approved',
                closed: 'Closed',
                reopened: 'Reopened',
            },
            ar: {
                draft: 'مسودة',
                open: 'مفتوحة',
                pending_review: 'قيد المراجعة',
                approved: 'معتمدة',
                closed: 'مغلقة',
                reopened: 'أُعيد فتحها',
            },
        };

        return labels[locale.value]?.[status] ?? String(status ?? '').replaceAll('_', ' ');
    };

    const settlementCycleLabel = (cycle) => {
        const labels = {
            en: {
                weekly: 'Weekly',
                biweekly: 'Bi-weekly',
                monthly: 'Monthly',
                quarterly: 'Quarterly',
            },
            ar: {
                weekly: 'أسبوعي',
                biweekly: 'كل أسبوعين',
                monthly: 'شهري',
                quarterly: 'ربع سنوي',
            },
        };

        return labels[locale.value]?.[cycle] ?? cycle;
    };

    const providerStatusLabel = (status) => {
        const labels = {
            en: { active: 'Active', inactive: 'Inactive' },
            ar: { active: 'نشط', inactive: 'غير نشط' },
        };

        return labels[locale.value]?.[status] ?? status;
    };

    const settlementItemStatusLabel = (status) => {
        const labels = {
            en: {
                matched: 'Matched',
                different_cost: 'Different cost',
                missing: 'Missing in invoice',
                extra: 'Extra in invoice',
                resolved: 'Resolved',
            },
            ar: {
                matched: 'متطابق',
                different_cost: 'تكلفة مختلفة',
                missing: 'غير موجود في الفاتورة',
                extra: 'إضافي في الفاتورة',
                resolved: 'تم حله',
            },
        };

        return labels[locale.value]?.[status] ?? String(status ?? '').replaceAll('_', ' ');
    };

    return {
        locale: computed(() => locale.value),
        isArabic: computed(() => locale.value === 'ar'),
        backArrow: computed(() => (locale.value === 'ar' ? '→' : '←')),
        forwardArrow: computed(() => (locale.value === 'ar' ? '←' : '→')),
        setLocale,
        t,
        paginationLabel,
        languageOptions,
        settlementStatusLabel,
        settlementCycleLabel,
        providerStatusLabel,
        settlementItemStatusLabel,
    };
}